export function isCatchTrophy(species: string, weight: number): boolean {
  const max = FISH_W_MAX[species];
  if (max == null || !Number.isFinite(weight)) return false;
  return weight > max + 1e-6;
}

export function getFishInfo(species: string): (FishSpeciesInfo & { wMax: number }) | null {
  const info = FISH_INFO[species];
  const wMax = FISH_W_MAX[species];
  if (!info || wMax == null) return null;
  return { ...info, wMax };
}
